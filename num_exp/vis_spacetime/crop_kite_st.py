"""Crop the Blender renders of fig:spacetime_kite and write the label anchors as TikZ coordinates.

  python3 crop_kite_st.py   ->  ../../graphics/spacetime-kite-{a,b}-blender.png (cropped in place, downscaled)
                                ../../graphics/spacetime-kite-{a,b}.anchors.tex (\\coordinate (<p>-<name>) ...)
Coordinates are normalized to the cropped image (origin bottom left), for a TikZ scope with
x={(img.south east)}, y={(img.north west)}. If vis/spacetime-kite-<p>-mask.png exists (render without background
mesh), the mesh is faded out with the distance from the object. The uncropped render is kept as
vis/spacetime-kite-<p>-raw.png, so that the script can be re-run.  (Adapted from dfg-unfitted/numexa/crop_spacetime.py.)
"""
import json, os, sys
import numpy as np
from PIL import Image
from scipy.ndimage import distance_transform_edt

FADE = (0.02, 0.08)
SCALE = 0.6                                  # downscale (the figure is printed at ~6 cm width)
G = "../../graphics/"
for p in sys.argv[1] if len(sys.argv) > 1 else "abcd":
    png = G + f"spacetime-kite-{p}-blender.png"
    A = json.load(open(png.replace(".png", ".anchors.json")))
    im = Image.open(png).convert("RGBA")
    raw = f"vis/spacetime-kite-{p}-raw.png"
    if list(im.size) == A["res"]:
        im.save(raw)
    elif os.path.exists(raw):
        im = Image.open(raw).convert("RGBA")
    else:
        sys.exit(f"{png} is already cropped and {raw} is missing: re-render first")
    W, H = im.size
    mask = f"vis/spacetime-kite-{p}-mask.png"
    if os.path.exists(mask):
        obj = np.asarray(Image.open(mask).convert("RGBA").getchannel("A")) > 40
        d = distance_transform_edt(~obj) / W
        s = np.clip((FADE[1] - d) / (FADE[1] - FADE[0]), 0, 1)
        s = s * s * (3 - 2 * s)
        a = np.asarray(im.getchannel("A")).astype(float)
        im.putalpha(Image.fromarray(np.where(obj, a, a * s).round().astype(np.uint8)))
    alpha = im.getchannel("A").point(lambda a: 255 if a > 40 else 0)
    l, t, r, b = alpha.getbbox()
    pad = 16
    l, t, r, b = max(l - pad, 0), max(t - pad, 0), min(r + pad, W), min(b + pad, H)
    cw, ch = r - l, b - t
    im.crop((l, t, r, b)).resize((round(cw * SCALE), round(ch * SCALE)), Image.LANCZOS).save(png, optimize=True)
    with open(G + f"spacetime-kite-{p}.anchors.tex", "w") as f:
        f.write(f"% generated by num_exp/vis_spacetime/crop_kite_st.py; panel ({p}), cropped image {cw}x{ch} px\n")
        for k, (x, y) in A["anchors"].items():
            f.write(f"\\coordinate ({p}-{k}) at ({(x * W - l) / cw:.4f},{1 - ((1 - y) * H - t) / ch:.4f});\n")
    print(p, (cw, ch), "aspect", round(cw / ch, 3))
